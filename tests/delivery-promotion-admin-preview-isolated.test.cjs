'use strict';
const assert=require('node:assert/strict');
const {makePromotionDraft,createDraftSession,previewPromotion}=require('./delivery-promotion-admin-preview-isolated.cjs');
const lines=[{productId:'a',type:'propio',allowedOriginIds:['a'],dispatchOriginId:'a'},
 {productId:'b',type:'propio',allowedOriginIds:['b'],dispatchOriginId:'b',specialFeeCup:2400}];
