assert.deepEqual(session.read().freeProductIds,['a']);
assert.equal(session.preview({...args,roadDistancesKm:{a:2}}).reason,'missing_verified_road_distance');
assert.equal(session.preview({...args,province:'Matanzas'}).reason,'outside_coverage');
assert.equal(session.edit({enabled:false,thresholdUsd:null,freeProductIds:['missing']}).ok,true);
