'use strict';
const assert=require('node:assert/strict');
const {createRegistry}=require('./delivery-warehouse-registry-isolated.cjs');
const r=createRegistry();
const throws=(f,msg)=>assert.throws(f,new RegExp(msg));
r.supplierAdd({id:'supplier1',name:'Nombre introducido por administrador'});
r.warehouseAdd({id:'first',type:'proveedor',supplierId:'supplier1',name:'Nombre editable',lat:23.13024,lng:-82.36028});
r.warehouseAdd({id:'own',type:'propio',name:'Almacén propio de ejemplo',lat:23.12,lng:-82.38});
r.assignProduct('laptop',['first','own']);
assert.deepEqual(r.resolve('laptop').map(x=>x.id),['first','own']);
const first=r.snapshot().warehouses.find(w=>w.id==='first');
assert.equal(first.lat,23.13024);
assert.equal(first.lng,-82.36028);
throws(()=>r.warehouseEdit('first',{name:'Cambio inválido'},0),'version_conflict');
r.warehouseEdit('first',{name:'Nombre definido desde la interfaz'},1);
assert.equal(r.snapshot().warehouses.find(w=>w.id==='first').version,2);
r.warehouseEdit('first',{lat:23.13025},2);
assert.equal(r.snapshot().audit.at(-1).action,'routing_change');
r.warehouseEdit('first',{active:false},3);
assert.deepEqual(r.resolve('laptop').map(x=>x.id),['own']);
r.warehouseEdit('first',{active:true},4);
r.supplierEdit('supplier1',{active:false});
assert.deepEqual(r.resolve('laptop').map(x=>x.id),['own']);
throws(()=>r.warehouseAdd({id:'bad',type:'propio',name:'X',lat:91,lng:0}),'invalid_coordinates');
throws(()=>r.warehouseAdd({id:'bad',type:'proveedor',supplierId:'unknown',name:'X',lat:23,lng:-82}),'supplier_required');
throws(()=>r.assignProduct('phone',['missing']),'invalid_assignment');
const snap=r.snapshot();snap.warehouses[0].name='tampered';
assert.notEqual(r.snapshot().warehouses[0].name,'tampered');
assert.equal(r.snapshot().revision,r.snapshot().audit.length);
console.log('PASS: supplier/warehouse CRUD, own/provider, multiple origins, versions, routing invalidation, no external IO');
