'use strict';
const assert=require('node:assert/strict');
const {quoteManagerServerContract}=require('./delivery-manager-server-contract-isolated.cjs');
const nowMs=1794600000000;
const principal={userId:'manager-1',role:'gestor',active:true,allowedCustomerIds:['customer-1']};
const address='Centro Habana, referencia';
const cart={id:'cart-1',ownerId:'manager-1',province:'La Habana',subtotalUsd:150,
 lines:[{productId:'p',type:'propio',allowedOriginIds:['origin'],dispatchOriginId:'origin'}],
 origins:[{id:'origin',type:'propio',active:true}]};
const customer={id:'customer-1',assignedManagerId:'manager-1',addresses:[{id:'addr-1',label:address,active:true,lastQuoteCup:600}]};
const settings={thresholdUsd:200,roundToCup:100,rateCupPerKm:200,minKm:3,minFeeCup:600,version:'v1'};
const route={destinationId:'saved:addr-1',cartId:'cart-1',settingsVersion:'v1',verified:true,verifiedAtMs:nowMs-1000,roadDistancesKm:{origin:3.4}};
const context={principal,customers:[customer],carts:[cart],routes:[route],settings,nowMs};
const request={customerKind:'habitual',customerId:'customer-1',addressId:'addr-1',cartId:'cart-1'};
const q=(req=request,ctx=context)=>quoteManagerServerContract({request:req,context:ctx});
let r=q();
assert.equal(r.available,true);
assert.equal(r.customerFeeCup,700);
assert.equal(r.previousDeliveryQuoteCup,600);
assert.equal(r.previousQuoteIsReferenceOnly,true);
assert.equal(r.destinationMode,'guardada');
assert.equal(r.orderCreated,false);
assert.equal(r.quoteSettingsVersion,'v1');
r=q(request,{...context,carts:[{...cart,subtotalUsd:200}]});
assert.equal(r.customerFeeCup,0);
assert.equal(r.calculatedDeliveryValueCup,700);
assert.equal(r.promotionCoveredCup,700);
r=q(request,{...context,carts:[{...cart,lines:[{...cart.lines[0],freeShipping:true}]}]});
assert.equal(r.customerFeeCup,0);
assert.equal(r.calculatedDeliveryValueCup,700);
const alternative='Habana Vieja, otra referencia';
const altReq={customerKind:'habitual',customerId:'customer-1',alternativeAddress:alternative,cartId:'cart-1'};
const altRoute={...route,destinationId:'alternative:'+alternative,roadDistancesKm:{origin:8}};
r=q(altReq,{...context,routes:[altRoute]});
assert.equal(r.available,true);
assert.equal(r.destinationMode,'alternativa');
assert.equal(r.customerFeeCup,1600);
assert.equal(r.previousDeliveryQuoteCup,null);
assert.equal(q(altReq).reason,'missing_fresh_verified_route');
const fresh='Plaza, referencia';
const newReq={customerKind:'nuevo',proposedAddress:fresh,cartId:'cart-1'};
r=q(newReq,{...context,routes:[{...route,destinationId:'new:'+fresh}]});
assert.equal(r.available,true);
assert.equal(r.customerKind,'nuevo');
assert.equal(r.previousDeliveryQuoteCup,null);
assert.equal(q({...request,feeCup:0}).reason,'invalid_contract');
assert.equal(q({...request,actorRole:'administrador_general'}).reason,'invalid_contract');
assert.equal(q({...request,roadDistancesKm:{origin:0}}).reason,'invalid_contract');
assert.equal(q(request,{...context,principal:{...principal,role:'cliente'}}).reason,'forbidden_principal');
assert.equal(q(request,{...context,principal:{...principal,active:false}}).reason,'forbidden_principal');
assert.equal(q(request,{...context,principal:{...principal,allowedCustomerIds:[]}}).reason,'customer_not_accessible');
assert.equal(q(request,{...context,customers:[{...customer,assignedManagerId:'another'}]}).reason,'customer_not_accessible');
assert.equal(q(request,{...context,carts:[{...cart,ownerId:'another'}]}).reason,'cart_not_accessible');
assert.equal(q({...request,addressId:'unknown'}).reason,'address_not_accessible');
assert.equal(q(request,{...context,routes:[{...route,verified:false}]}).reason,'missing_fresh_verified_route');
assert.equal(q(request,{...context,routes:[{...route,verifiedAtMs:nowMs-16*60*1000}]}).reason,'missing_fresh_verified_route');
assert.equal(q(request,{...context,routes:[{...route,settingsVersion:'old'}]}).reason,'missing_fresh_verified_route');
assert.equal(q(request,{...context,routes:[{...route,roadDistancesKm:{}}]}).reason,'invalid_route');
assert.equal(q({...newReq,customerId:'customer-1'}).reason,'invalid_new_customer');
assert.equal(q({...request,proposedAddress:'x'}).reason,'unexpected_new_address');
console.log('PASS manager server contract: roles, ownership, saved/new/alternative addresses, route freshness, free ledger, reject client overrides');
