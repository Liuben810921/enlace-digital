'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const {makeRouteRequest,readRouteDistance}=require('./delivery-route-adapter-isolated.cjs');
const html=fs.readFileSync('index.html','utf8');
const scripts=[...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)].map(x=>x[1]);
for(const script of scripts)new vm.Script(script);
const script=scripts.find(x=>x.includes('function edParseOsmAndCoordinates('));
assert(script);
const start=script.indexOf('function edParseOsmAndCoordinates(');
const end=script.indexOf('const ED_DELIVERY_DESTINATIONS_KEY=',start);
const elements={};
const ctx={document:{getElementById:id=>elements[id]||(elements[id]={value:''})},alert:message=>{ctx.alertMessage=message},Number,String,Math};
vm.createContext(ctx);vm.runInContext(script.slice(start,end),ctx);
const parse=s=>vm.runInContext('edParseOsmAndCoordinates('+JSON.stringify(s)+')',ctx);
assert.equal(parse('23.13024 -82.36028').lat,23.13024);
assert.equal(parse('23.13024, -82.36028').lng,-82.36028);
assert.equal(parse('23.13024° N, 82.36028° W').lng,-82.36028);
for(const bad of ['','91 -82','23.13 -181','hello','23.13'])assert.equal(parse(bad),null);
elements.source={value:'23.13024 -82.36028'};
assert.equal(vm.runInContext("edApplyOsmAndCoordinates('source','lat','lng')",ctx),true);
assert.equal(elements.lat.value,23.13024);
assert.equal(elements.lng.value,-82.36028);
assert.match(html,/id="edOriginOsmAnd"/);
assert.match(html,/id="edDestinationOsmAnd"/);
const req=makeRouteRequest({lat:23.13024,lng:-82.36028},{lat:23.12,lng:-82.35});
assert.equal(req.ok,true);
assert.deepEqual(req.coordinates[0],[-82.36028,23.13024]);
assert.equal(req.requiresExternalService,true);
assert.equal(makeRouteRequest({lat:99,lng:0},{lat:23,lng:-82}).reason,'invalid_coordinates');
assert.equal(readRouteDistance({code:'Ok',routes:[{distance:3970}]}).roadDistanceKm,3.97);
assert.equal(readRouteDistance({code:'NoRoute',routes:[]}).reason,'route_unavailable');
assert.equal(readRouteDistance({code:'Ok',routes:[{distance:-1}]}).reason,'invalid_route_distance');
console.log('PASS OsmAnd paste and offline OSRM-compatible route adapter');
