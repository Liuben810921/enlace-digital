'use strict';
const assert=require('node:assert/strict');
const {assessRoute,evaluateRouteMatrix,quoteWithValidation}=require('./delivery-route-validation-isolated.cjs');
const ok=assessRoute({osmandKm:7.4,engineKm:7.8});
assert.equal(ok.approved,true);
assert.equal(ok.feeStatus,'eligible_for_quote');
const near=assessRoute({osmandKm:2,engineKm:2.45});
assert.equal(near.approved,true);
assert.equal(near.absoluteDeviationKm,0.4500000000000002);
const bad=assessRoute({osmandKm:7.4,engineKm:9.2});
assert.equal(bad.approved,false);
assert.equal(bad.reason,'distance_discrepancy');
assert.equal(bad.feeStatus,'pending_confirmation');
assert.equal(assessRoute({osmandKm:7.4,engineKm:7.4,providerStatus:'timeout'}).reason,'provider_unavailable');
assert.equal(assessRoute({osmandKm:7.4,engineKm:NaN}).reason,'invalid_measurement');
assert.equal(assessRoute({osmandKm:0,engineKm:0}).approved,false);
assert.equal(evaluateRouteMatrix([]).reason,'no_reference_routes');
const matrix=evaluateRouteMatrix([{id:'short',osmandKm:2,engineKm:2.2},{id:'long',osmandKm:12,engineKm:15}]);
assert.equal(matrix.approved,false);
assert.equal(matrix.passed,1);
assert.equal(matrix.total,2);
assert.equal(quoteWithValidation({assessment:bad,quote:{available:true,feeCup:1800}}).feeStatus,'pending_confirmation');
assert.equal(quoteWithValidation({assessment:ok,quote:{available:true,feeCup:1560}}).feeCup,1560);
assert.equal(quoteWithValidation({assessment:ok,quote:{available:false}}).available,false);
console.log('PASS offline OsmAnd route validation: tolerances, unavailable, discrepancy, tariff pending');
