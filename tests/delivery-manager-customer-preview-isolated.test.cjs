'use strict';
const assert=require('node:assert/strict');
const {previewCustomerDelivery}=require('./delivery-manager-customer-preview-isolated.cjs');
const origins=[{id:'own',type:'propio',active:true},{id:'supplier',type:'proveedor',supplierId:'s1',active:true}];
const lines=[{productId:'laptop',type:'propio',allowedOriginIds:['own'],dispatchOriginId:'own'},
 {productId:'speaker',type:'proveedor',supplierId:'s1',allowedOriginIds:['supplier'],dispatchOriginId:'supplier'}];
const quoteArgs={province:'La Habana',lines,origins,roadDistancesKm:{own:2,supplier:3.4},orderSubtotalUsd:150,freeShippingThresholdUsd:200,roundToCup:100};
const returning={kind:'habitual',savedAddressId:'dest-1',savedAddress:'Centro Habana, punto de referencia',lastDeliveryQuoteCup:600};
const newer={kind:'nuevo',proposedAddress:'Plaza de la Revolución, referencia'};
const q=(customer,extra={})=>previewCustomerDelivery({actorRole:'gestor',customer,quoteArgs,...extra});
let r=q(returning);
assert.equal(r.available,true);
assert.equal(r.customerFeeCup,700);
assert.equal(r.calculatedDeliveryValueCup,700);
assert.equal(r.destinationMode,'guardada');
assert.equal(r.previousDeliveryQuoteCup,600);
assert.equal(r.historicalQuoteDifferenceCup,100);
assert.equal(r.previousQuoteIsReferenceOnly,true);
assert.equal(r.quoteUsesCurrentSettings,true);
assert.equal(r.orderCreated,false);
r=q(returning,{quoteArgs:{...quoteArgs,roadDistancesKm:{own:2,supplier:5.3},roundToCup:100}});
assert.equal(r.customerFeeCup,1100);
assert.equal(r.previousDeliveryQuoteCup,600);
assert.equal(r.historicalQuoteDifferenceCup,500);
r=q(returning,{alternativeAddress:'Habana Vieja, otra referencia',quoteArgs:{...quoteArgs,roadDistancesKm:{own:4.1,supplier:8}}});
assert.equal(r.destinationMode,'alternativa');
assert.equal(r.destinationLabel,'Habana Vieja, otra referencia');
assert.equal(r.customerFeeCup,1600);
assert.equal(r.previousDeliveryQuoteCup,600);
r=q(newer);
assert.equal(r.destinationMode,'nueva');
assert.equal(r.previousDeliveryQuoteCup,null);
assert.equal(r.customerFeeCup,700);
r=q(newer,{alternativeAddress:'Nuevo Vedado, referencia'});
assert.equal(r.destinationMode,'alternativa');
assert.equal(r.destinationLabel,'Nuevo Vedado, referencia');
r=q(returning,{quoteArgs:{...quoteArgs,orderSubtotalUsd:200}});
assert.equal(r.customerFeeCup,0);
assert.equal(r.calculatedDeliveryValueCup,700);
assert.equal(r.promotionCoveredCup,700);
assert.equal(r.previousDeliveryQuoteCup,600);
r=q(returning,{quoteArgs:{...quoteArgs,lines:[{...lines[0],freeShipping:true},lines[1]]}});
assert.equal(r.customerFeeCup,0);
assert.equal(r.calculatedDeliveryValueCup,700);
r=q(returning,{quoteArgs:{...quoteArgs,lines:[{...lines[0],specialFeeCup:1250},lines[1]]}});
assert.equal(r.customerFeeCup,1300);
assert.equal(r.calculatedDeliveryValueCup,1300);
assert.equal(q(returning,{quoteArgs:{...quoteArgs,roadDistancesKm:{own:2}}}).reason,'missing_verified_road_distance');
assert.equal(q(returning,{quoteArgs:{...quoteArgs,feeCup:600}}).reason,'forbidden_quote_override');
assert.equal(q(returning,{actorRole:'cliente'}).reason,'forbidden_role');
assert.equal(q({kind:'habitual',savedAddress:'x'}).reason,'missing_saved_address');
assert.equal(q({kind:'nuevo',proposedAddress:''}).reason,'missing_destination_address');
assert.equal(q({kind:'nuevo',savedAddress:'fake',proposedAddress:'x'}).reason,'new_customer_has_saved_address');
assert.equal(q({...returning,lastDeliveryQuoteCup:'600'}).reason,'invalid_last_reference');
assert.equal(q(returning,{alternativeAddress:''}).reason,'invalid_alternative_address');
assert.equal(q(returning,{quoteArgs:{...quoteArgs,province:'Matanzas'}}).reason,'outside_coverage');
console.log('PASS manager customer previews: new/returning, saved/alternative, historical reference only, current tariffs, free ledger, fail closed');
