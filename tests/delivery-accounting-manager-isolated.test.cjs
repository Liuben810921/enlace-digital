'use strict';
const assert=require('node:assert/strict');
const {quoteDeliveryAccounting,validateAdminDeliverySettings,previewForManager}=require('./delivery-accounting-manager-isolated.cjs');
const origins=[{id:'a',type:'propio',active:true,lat:23.13,lng:-82.36},{id:'b',type:'proveedor',supplierId:'s',active:true,lat:23.14,lng:-82.37}];
const lines=[{productId:'a',type:'propio',allowedOriginIds:['a'],dispatchOriginId:'a'},{productId:'b',type:'proveedor',supplierId:'s',allowedOriginIds:['b'],dispatchOriginId:'b'}];
const base={province:'La Habana',lines,origins,roadDistancesKm:{a:3,b:3.4},orderSubtotalUsd:200,freeShippingThresholdUsd:200};
const q=extra=>quoteDeliveryAccounting({...base,...extra});
let r=q({});
assert.equal(r.available,true);
assert.equal(r.calculatedDeliveryValueCup,700);
assert.equal(r.customerFeeCup,0);
assert.equal(r.promotionCoveredCup,700);
assert.equal(r.accountingStatus,'estimated_not_actual_cost');
assert.equal(r.freeReason,'subtotal_threshold');
r=q({orderSubtotalUsd:199.99});
assert.equal(r.calculatedDeliveryValueCup,700);
assert.equal(r.customerFeeCup,700);
assert.equal(r.promotionCoveredCup,0);
r=q({orderSubtotalUsd:199.99,roundToCup:50});
assert.equal(r.customerFeeCup,700);
r=q({orderSubtotalUsd:199.99,roadDistancesKm:{a:3,b:3.21}});
assert.equal(r.customerFeeCup,700);
r=q({orderSubtotalUsd:199.99,roadDistancesKm:{a:3,b:3.01}});
assert.equal(r.customerFeeCup,700);
r=q({orderSubtotalUsd:199.99,lines:[lines[0]]});
assert.equal(r.customerFeeCup,600);
r=q({orderSubtotalUsd:199.99,lines:[{...lines[0],specialFeeCup:1250}]});
assert.equal(r.calculatedDeliveryValueCup,1300);
r=q({orderSubtotalUsd:199.99,lines:[{...lines[0],specialFeeCup:1250,freeShipping:true}]});
assert.equal(r.calculatedDeliveryValueCup,1300);
assert.equal(r.customerFeeCup,0);
assert.equal(r.promotionCoveredCup,1300);
assert.equal(q({roadDistancesKm:{a:3}}).reason,'missing_verified_road_distance');
assert.equal(q({roundToCup:0}).reason,'invalid_rounding_increment');
assert.equal(q({roundToCup:10.5}).reason,'invalid_rounding_increment');
assert.equal(validateAdminDeliverySettings({actorRole:'gestor',thresholdUsd:200,roundToCup:100}).reason,'forbidden_role');
assert.equal(validateAdminDeliverySettings({actorRole:'administrador_general',thresholdUsd:200,roundToCup:100}).ok,true);
assert.equal(validateAdminDeliverySettings({actorRole:'administrador_general',thresholdUsd:-1,roundToCup:100}).reason,'invalid_threshold');
assert.equal(previewForManager({...base,actorRole:'gestor'}).previewOnly,true);
assert.equal(previewForManager({...base,actorRole:'gestor'}).orderCreated,false);
assert.equal(previewForManager({...base,actorRole:'cliente'}).reason,'forbidden_role');
assert.equal(previewForManager({...base,actorRole:'gestor',roadDistancesKm:{}}).reason,'missing_verified_road_distance');
for(const [distance,expected] of [[0,600],[2.99,600],[3,600],[3.01,700],[3.5,700],[4,800],[4.01,900]]){
 const result=q({orderSubtotalUsd:199.99,lines:[lines[0]],roadDistancesKm:{a:distance,b:3.4}});
 assert.equal(result.customerFeeCup,expected,'distance '+distance);
 assert.equal(result.calculatedDeliveryValueCup,expected);
 assert.equal(result.promotionCoveredCup,0);
}
for(const [special,expected] of [[0,600],[601,700],[699,700],[700,700],[701,800],[1250,1300]]){
 const result=q({orderSubtotalUsd:200,lines:[{...lines[0],specialFeeCup:special}]});
 assert.equal(result.customerFeeCup,0);
 assert.equal(result.calculatedDeliveryValueCup,expected);
 assert.equal(result.promotionCoveredCup,expected);
}
assert.equal(q({orderSubtotalUsd:200,lines:[{...lines[0],freeShipping:true}],freeShippingThresholdUsd:null}).freeReason,'product_promotion');
assert.equal(q({orderSubtotalUsd:199.99,roundToCup:1,lines:[{...lines[0],specialFeeCup:601}]}).customerFeeCup,601);
assert.equal(q({orderSubtotalUsd:199.99,roundToCup:100,lines:[{...lines[0],specialFeeCup:601}]}).customerFeeCup,700);
console.log('PASS accounting/manager: gross vs customer fee, rounding, promotion, role guard, preview only');
