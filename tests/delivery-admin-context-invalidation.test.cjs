'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const scripts=[...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)].map(m=>m[1]);
for(const script of scripts)new vm.Script(script);
const source=scripts.join('\n'),start=source.indexOf("const ED_DELIVERY_ORIGINS_KEY="),end=source.indexOf("function deliveryBarrios(){",start);
assert(start>=0&&end>start);
const store=new Map(),elements={};const el=id=>elements[id]||(elements[id]={value:'',textContent:'',style:{},scrollIntoView(){}});
const ctx={localStorage:{getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v)},document:{getElementById:el},municipios:['Playa'],esc:s=>String(s).replaceAll('<','&lt;'),alert:s=>{ctx.alertMessage=s},prompt:()=>ctx.nextName,adminTab:t=>{ctx.lastTab=t},Date,Math,Number,JSON};
vm.createContext(ctx);vm.runInContext(source.slice(start,end),ctx);
const call=x=>vm.runInContext(x,ctx);
el('edSupplierName').value='Proveedor temporal';
call('edDeliverySupplierAdd()');
const supplierId=call('edDeliverySuppliersRead()[0].id');
ctx.nextName='Proveedor elegido';
call('edDeliverySupplierEdit('+JSON.stringify(supplierId)+')');
assert.equal(call('edDeliverySuppliersRead()[0].name'),'Proveedor elegido');
for(const [id,value] of Object.entries({edOriginId:'',edOriginName:'Nombre pendiente',edOriginType:'proveedor',edOriginSupplier:supplierId,edOriginMunicipality:'Playa',edOriginAddress:'Ubicación de proveedor',edOriginLat:'23.13024',edOriginLng:'-82.36028'}))el(id).value=value;
