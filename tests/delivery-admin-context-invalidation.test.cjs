call('edDeliveryOriginSave()');
assert.equal(call('edDeliveryOriginsRead()[0].version'),2);
assert.equal(call('edDeliveryQuoteStillValid('+JSON.stringify(snapshot)+')'),false);
const newSnapshot=call('edDeliveryQuoteSnapshot()');
call('edDeliveryOriginToggle('+JSON.stringify(warehouseId)+')');
assert.equal(call('edDeliveryQuoteStillValid('+JSON.stringify(newSnapshot)+')'),false);
call('edDeliverySupplierToggle('+JSON.stringify(supplierId)+')');
assert.equal(call('edDeliverySuppliersRead()[0].active'),false);
