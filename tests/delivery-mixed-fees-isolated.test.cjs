'use strict';
const assert=require('node:assert/strict');
const {quoteMixedDelivery}=require('./delivery-mixed-fees-isolated.cjs');
const origins=[{id:'a',type:'propio',active:true},{id:'b',type:'propio',active:true},{id:'far-unused',type:'propio',active:true}];
const item=(id,origin,extra={})=>({productId:id,type:'propio',allowedOriginIds:[origin],dispatchOriginId:origin,...extra});
const run=(lines,extra={})=>quoteMixedDelivery({province:'La Habana',lines,origins,roadDistancesKm:{a:2,b:8,'far-unused':100},...extra});
const normal=run([item('small','a'),item('medium','b')]);
assert.equal(normal.available,true);
assert.equal(normal.farthestKm,8);
assert.equal(normal.feeCup,1600);
assert.deepEqual(normal.distinctOriginIds,['a','b']);
assert.equal(run([item('small','a')]).feeCup,600);
assert.equal(run([item('large','a',{specialFeeCup:2400})]).feeCup,2400);
assert.equal(run([item('large','b',{specialFeeCup:900})]).feeCup,1600);
assert.equal(run([item('large','a',{specialFeeCup:2400}),item('large2','b',{specialFeeCup:3000})]).feeCup,3000);
assert.equal(run([item('large','a',{specialFeeCup:2400}),item('large2','b',{specialFeeCup:3000})]).maxSpecialFeeCup,3000);
assert.equal(run([item('free','a',{freeShipping:true}),item('paid','b')]).feeCup,1600);
assert.equal(run([item('free','a',{freeShipping:true,specialFeeCup:9000}),item('paid','b')]).maxSpecialFeeCup,null);
assert.equal(run([item('free','a',{freeShipping:true}),item('free2','b',{freeShipping:true})]).feeCup,0);
assert.equal(run([item('large','a',{specialFeeCup:2400}),item('paid','b')],{orderFreeShipping:true}).feeCup,0);
assert.equal(run([item('large','a',{specialFeeCup:2400}),item('paid','b')],{orderFreeShipping:true}).mode,'free');
assert.equal(run([item('bad','a',{specialFeeCup:-1})]).reason,'invalid_product_special_fee');
assert.equal(run([item('bad','a',{specialFeeCup:'100'})]).reason,'invalid_product_special_fee');
assert.equal(run([item('bad','a',{freeShipping:'yes'})]).reason,'invalid_product_free_shipping');
assert.equal(run([item('dup','a'),item('dup','b')]).reason,'duplicate_or_invalid_product');
assert.equal(run([item('a','a')],{roadDistancesKm:{}}).reason,'missing_verified_road_distance');
assert.equal(run([item('a','a',{freeShipping:true})],{roadDistancesKm:{}}).reason,'missing_verified_road_distance');
assert.equal(run([item('a','a')],{province:'Matanzas'}).reason,'outside_coverage');
assert.equal(run([item('a','a')],{orderFreeShipping:'true'}).reason,'invalid_free_shipping');
assert.equal(run([item('a','a'),item('b','b')],{roadDistancesKm:{a:2,b:3.01}}).feeCup,602);
assert.equal(run([item('a','a')],{settings:{rateCupPerKm:250,minFeeCup:900}}).feeCup,900);
console.log('PASS mixed-cart policy: single charge, special floor, free precedence, effective origins, invalid data, min distance');
