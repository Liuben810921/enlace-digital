'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync(require('node:path').join(__dirname,'fixtures/delivery-manager-mobile-demo.html'),'utf8');
const ids=['customerType','savedArea','savedAddress','lastFee','addressMode','newArea','newAddress','alternativeArea','alternativeAddress','subtotal','distance','special','productFree','calculate','reset','feedback','results','gross','customerFee','covered','quoteReason'];
for(const id of ids)assert.match(html,new RegExp('id="'+id+'"'));
for(const id of ['customerType','savedAddress','addressMode','newAddress','alternativeAddress','subtotal','distance','special','productFree'])assert.match(html,new RegExp('for="'+id+'"'));
assert.match(html,/name="viewport"/);
assert.match(html,/aria-live="polite"/);
assert.match(html,/@media\(max-width:360px\)/);
assert.doesNotMatch(html,/\bfetch\s*\(|XMLHttpRequest|supabase|localStorage|sessionStorage|navigator\.geolocation/);
const els=new Map(ids.map(id=>[id,{id,type:id==='productFree'?'checkbox':'text',value:'',checked:false,hidden:id==='results',textContent:'',listeners:{},addEventListener(e,fn){this.listeners[e]=fn;}}]));
const script=html.match(/<script>([\s\S]*?)<\/script>/)[1];
vm.runInNewContext(script,{document:{getElementById:id=>els.get(id)},Number,Object,Math},{timeout:1000});
const e=id=>els.get(id);
e('reset').listeners.click();
assert.equal(e('customerType').value,'nuevo');
assert.equal(e('savedArea').hidden,true);
e('calculate').listeners.click();
assert.equal(e('gross').textContent,'700 CUP');
assert.equal(e('customerFee').textContent,'700 CUP');
assert.equal(e('covered').textContent,'0 CUP');
assert.match(e('quoteReason').textContent,/Plaza de la Revolución/);
e('customerType').value='habitual';e('customerType').listeners.change();
assert.equal(e('savedArea').hidden,false);
assert.equal(e('newArea').hidden,true);
assert.equal(e('results').hidden,true);
e('savedAddress').value='Centro Habana, punto de referencia';
e('calculate').listeners.click();
assert.equal(e('customerFee').textContent,'700 CUP');
assert.match(e('lastFee').textContent,/600 CUP/);
assert.match(e('quoteReason').textContent,/Centro Habana/);
e('addressMode').value='alternativa';e('addressMode').listeners.change();
assert.equal(e('alternativeArea').hidden,false);
e('distance').value='8';
e('calculate').listeners.click();
assert.equal(e('customerFee').textContent,'1600 CUP');
assert.match(e('quoteReason').textContent,/Habana Vieja/);
e('subtotal').value='200';e('calculate').listeners.click();
assert.equal(e('gross').textContent,'1600 CUP');
assert.equal(e('customerFee').textContent,'0 CUP');
assert.equal(e('covered').textContent,'1600 CUP');
e('subtotal').value='150';e('productFree').checked=true;e('calculate').listeners.click();
assert.equal(e('customerFee').textContent,'0 CUP');
e('special').value='1950';e('calculate').listeners.click();
assert.equal(e('gross').textContent,'2000 CUP');
e('alternativeAddress').value='';e('calculate').listeners.click();
assert.equal(e('results').hidden,true);
assert.match(e('feedback').textContent,/dirección válida/);
e('reset').listeners.click();
assert.equal(e('customerType').value,'nuevo');
assert.equal(e('productFree').checked,false);
assert.equal(e('results').hidden,true);
console.log('PASS manager mobile demo: new/returning, saved/alternative, historic-only, recalculation, free ledger, validation, reset');
