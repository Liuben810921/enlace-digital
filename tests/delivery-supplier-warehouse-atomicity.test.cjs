'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const scripts=[...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)].map(x=>x[1]);
for(const s of scripts)new vm.Script(s);
const src=scripts.join('\n'),start=src.indexOf('const ED_DELIVERY_ORIGINS_KEY='),end=src.indexOf('function deliveryBarrios(){',start);
assert(start>=0&&end>start);
const store=new Map(),fail=new Set(),nodes={};let denyRollback=false,attempts=0;
const el=id=>nodes[id]||(nodes[id]={value:'',style:{}});
const ctx={localStorage:{getItem:k=>{if(fail.has('get:'+k))throw Error('read');return store.get(k)||null},setItem:(k,v)=>{if(fail.has('set:'+k)||denyRollback&&k==='ed_delivery_suppliers_demo_v1'&&++attempts===2)throw Error('write');store.set(k,v)},removeItem:k=>store.delete(k)},document:{getElementById:el},esc:String,municipios:['Playa'],Date,Math,Number,JSON,alert:s=>{ctx.warning=s},adminTab:()=>{}};
vm.createContext(ctx);vm.runInContext(src.slice(start,end),ctx);
const call=s=>vm.runInContext(s,ctx),supplier='ed_delivery_suppliers_demo_v1',origins='ed_delivery_origins_demo_v1',rev='ed_delivery_context_revision_demo_v1';
store.set(supplier,JSON.stringify([{id:'s',name:'Original',active:true}]));
store.set(origins,JSON.stringify([{id:'a',type:'proveedor',supplierId:'s',name:'A',active:true}]));
store.set('ed_product_origins_demo_v1',JSON.stringify({item:['a']}));
const snap=call('edDeliveryQuoteSnapshot()');
fail.add('set:'+rev);
call("edDeliverySupplierToggle('s')");
assert.equal(JSON.parse(store.get(supplier))[0].active,true);
assert.equal(call('edDeliveryQuoteStillValid('+JSON.stringify(snap)+')'),true);
call("edDeliveryOriginToggle('a')");
assert.equal(JSON.parse(store.get(origins))[0].active,true);
fail.delete('set:'+rev);
call("edDeliverySupplierToggle('s')");
assert.equal(JSON.parse(store.get(supplier))[0].active,false);
assert.equal(call('edDeliveryQuoteStillValid('+JSON.stringify(snap)+')'),false);
call("edDeliverySupplierToggle('s')");
assert.equal(JSON.parse(store.get(supplier))[0].active,true);
fail.add('set:'+rev);
denyRollback=true;attempts=0;
call("edDeliverySupplierToggle('s')");
assert.equal(call('edDeliveryIsQuarantined()'),true);
assert.equal(call('edDeliveryQuoteStillValid('+JSON.stringify(call('edDeliveryQuoteSnapshot()'))+')'),false);
assert.match(call('edDeliveryOriginsPanel()'),/Verificar y desbloquear/);
assert.equal(call("edDeliveryPersistAndInvalidate('ed_delivery_origins_demo_v1',[],'warehouse_status')"),false);
console.log('PASS supplier and warehouse rollback, successful invalidation, quarantine on rollback failure, blocked mutations and mobile alert');
