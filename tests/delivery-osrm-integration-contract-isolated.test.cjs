'use strict';
const assert=require('node:assert/strict');
const {prepareRoadRoute,acceptRoadRoute}=require('./delivery-osrm-integration-contract-isolated.cjs');
const origin={id:'warehouse_1',lat:23.13,lng:-82.38,verified:true};
const destination={id:'destination_1',lat:23.11,lng:-82.36,verified:true};
const plan=prepareRoadRoute({origin,destination,province:'La Habana',cartographyVersion:'osm-fixture-v1'});
assert.equal(plan.ready,true);
assert.deepEqual(plan.request.coordinates,[[-82.38,23.13],[-82.36,23.11]]);
const envelope={trustedBackend:true,originId:origin.id,destinationId:destination.id,cartographyVersion:'osm-fixture-v1',measuredAtMs:1000,response:{code:'Ok',routes:[{distance:4700}]}};
const accept=(e=envelope,p=plan,t=1500)=>acceptRoadRoute({plan:p,envelope:e,nowMs:t,maxAgeMs:1000});
assert.equal(accept().roadDistanceKm,4.7);
assert.equal(accept({...envelope,destinationId:'other'}).feeStatus,'pending_confirmation');
assert.equal(accept({...envelope,cartographyVersion:'osm-fixture-v2'}).reason,'route_provenance_mismatch');
assert.equal(accept({...envelope,trustedBackend:false}).available,false);
assert.equal(accept(envelope,plan,2000).reason,'route_expired');
assert.equal(accept({...envelope,measuredAtMs:1600}).reason,'route_expired');
assert.equal(accept({...envelope,response:{code:'NoRoute',routes:[]}}).reason,'route_unavailable');
assert.equal(accept({...envelope,response:{code:'Ok',routes:[{distance:-1}]}}).reason,'invalid_route_distance');
assert.equal(prepareRoadRoute({origin,destination,province:'Matanzas',cartographyVersion:'v1'}).reason,'outside_coverage');
assert.equal(prepareRoadRoute({origin:{...origin,verified:false},destination,province:'La Habana',cartographyVersion:'v1'}).reason,'location_not_verified');
assert.equal(prepareRoadRoute({origin:{...origin,lat:91},destination,province:'La Habana',cartographyVersion:'v1'}).reason,'invalid_coordinates');
console.log('PASS offline OSRM provenance, WGS84 coordinate order, version, TTL, fail-closed unavailable routes');
