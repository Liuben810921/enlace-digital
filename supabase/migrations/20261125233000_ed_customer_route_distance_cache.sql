alter table public.clientes_direcciones_entrega
  add column if not exists geocodificacion_precision text,
  add column if not exists geocodificacion_direccion text;

alter table public.clientes_direcciones_entrega
  drop constraint if exists clientes_direcciones_entrega_geocodificacion_precision_check;
alter table public.clientes_direcciones_entrega
  add constraint clientes_direcciones_entrega_geocodificacion_precision_check
  check (geocodificacion_precision is null or geocodificacion_precision in ('address','street','coordinates'));

create table if not exists public.clientes_direcciones_rutas (
  id bigint generated by default as identity primary key,
  direccion_entrega_id bigint not null references public.clientes_direcciones_entrega(id) on delete cascade,
  punto_salida_id text not null check (length(punto_salida_id) between 1 and 160),
  origen_latitud double precision not null check (origen_latitud between 22.7 and 23.3),
  origen_longitud double precision not null check (origen_longitud between -83.0 and -81.9),
  destino_latitud double precision not null check (destino_latitud between 22.7 and 23.3),
  destino_longitud double precision not null check (destino_longitud between -83.0 and -81.9),
  distancia_km numeric(9,3) not null check (distancia_km >= 0 and distancia_km <= 300),
  duracion_segundos numeric(12,3) not null check (duracion_segundos >= 0),
  precision_destino text not null check (precision_destino in ('address','street','coordinates')),
  proveedor text not null default 'Geoapify' check (proveedor = 'Geoapify'),
  version_ruta text not null default 'geoapify-drive-v1',
  calculado_en timestamptz not null default now(),
  constraint clientes_direcciones_rutas_direccion_origen_key unique (direccion_entrega_id,punto_salida_id)
);

create index if not exists clientes_direcciones_rutas_direccion_idx
  on public.clientes_direcciones_rutas (direccion_entrega_id, version_ruta);

alter table public.clientes_direcciones_rutas enable row level security;
revoke all on table public.clientes_direcciones_rutas from public, anon, authenticated;
grant select, insert, update, delete on table public.clientes_direcciones_rutas to service_role;
grant usage, select on sequence public.clientes_direcciones_rutas_id_seq to service_role;

