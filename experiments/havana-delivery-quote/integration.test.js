'use strict';
const assert=require('node:assert/strict');
const {validateConfiguration,updateConfiguration,adaptCheckoutDelivery}=require('./integration.js');
const {quoteDelivery}=require('./quote.js');
const config={schemaVersion:1,revision:3,suppliers:[{id:'s',name:'Proveedor ficticio',active:true}],origins:[{id:'a',name:'Almacén A',type:'propio',active:true},{id:'b',name:'Almacén B',type:'proveedor',supplierId:'s',active:true}],destinations:[{id:'d',name:'Destino',municipality:'Playa',address:'Referencia ficticia'}]};
const routes=[{originId:'a',destinationId:'d',km:2,status:'verified',contextRevision:3},{originId:'b',destinationId:'d',km:7,status:'verified',contextRevision:3}];
let n=0;const check=(condition)=>{assert.ok(condition);n++};
const run=overrides=>adaptCheckoutDelivery({configuration:config,expectedRevision:3,destinationId:'d',routes,rateCupPerKm:200,quoteDelivery,...overrides});
check(validateConfiguration(config).ok);
check(validateConfiguration({...config,schemaVersion:2}).reason==='INVALID_VERSION');
check(validateConfiguration({...config,origins:[config.origins[0],config.origins[0]]}).reason==='INVALID_IDS');
check(validateConfiguration({...config,origins:[{...config.origins[1],supplierId:'missing'}]}).reason==='INVALID_ORIGIN');
check(updateConfiguration(config,2,{...config,revision:4}).status==='CONFLICT');
check(updateConfiguration(config,3,{...config,revision:3}).reason==='REVISION_NOT_INCREMENTED');
const updated=updateConfiguration(config,3,{...config,revision:4});check(updated.status==='ACCEPTED'&&updated.revision===4);
check(run().status==='COTIZACION_SIMULADA');
check(run().deliveryFeeCup===1400&&run().originId==='b');
check(run().productTotalAdjustment===0&&run().collection==='DIRECT_TO_COURIER');
check(run({specialFeeCup:900}).deliveryFeeCup===900);
check(run({expectedRevision:2}).reason==='STALE_REVISION');
check(run({destinationId:'missing'}).reason==='UNKNOWN_DESTINATION');
check(run({routes:[]}).reason==='ROAD_DISTANCE_MISSING');
check(run({routes:[routes[0]]}).status==='PENDIENTE');
check(run({routes:routes.map(r=>({...r,status:'synthetic'}))}).reason==='ROAD_DISTANCE_UNVERIFIED');
check(run({quarantined:true}).reason==='QUARANTINE');
check(run({quoteDelivery:null}).reason==='QUOTE_UNAVAILABLE');
check(run({rateCupPerKm:0}).reason==='INVALID_TARIFF');
check(run({configuration:{...config,revision:4}}).reason==='STALE_REVISION');
check(run({routes:[...routes,routes[0]]}).reason==='ROAD_DISTANCE_MISSING');
check(run({configuration:{...config,suppliers:[{...config.suppliers[0],active:false}]}}).deliveryFeeCup===600);
check(run({configuration:{...config,origins:[]}}).reason==='NO_ACTIVE_ORIGINS');
check(run({minKm:5,routes:[{...routes[0],km:1},{...routes[1],km:2}]}).deliveryFeeCup===1000);
console.log(`PASS ${n} offline delivery integration assertions`);
