'use strict';
const assert=require('node:assert/strict');
const {selectCartOrigins,quoteCartDelivery}=require('./cart-origins.js');
const {quoteDelivery}=require('./quote.js');
const configuration={schemaVersion:1,revision:5,suppliers:[{id:'s',name:'Proveedor',active:true}],origins:[{id:'a',name:'Propio A',type:'propio',active:true},{id:'b',name:'Proveedor B',type:'proveedor',supplierId:'s',active:true},{id:'c',name:'Propio C',type:'propio',active:true}],destinations:[{id:'d',name:'Destino',municipality:'Playa',address:'Ficticia'}]};
const associations={p1:['a'],p2:['b'],p3:['a','b']};
const routes=[{originId:'a',destinationId:'d',km:2,status:'verified',contextRevision:5},{originId:'b',destinationId:'d',km:7,status:'verified',contextRevision:5}];
const cart=[{productId:'p1',quantity:2},{productId:'p2',quantity:1}];
const args={configuration,cart,associations,expectedRevision:5,routes,destinationId:'d',rateCupPerKm:200,quoteDelivery};
let count=0;function check(condition){assert.ok(condition);count++}
const quote=x=>quoteCartDelivery({...args,...x});
check(selectCartOrigins(args).origins.map(o=>o.id).join(',')==='a,b');
check(quote().deliveryFeeCup===1400);
check(quote().originId==='b');
check(quote({cart:[cart[0]]}).deliveryFeeCup===600);
check(quote({cart:[cart[0]]}).originId==='a');
check(quote({cart:[{productId:'p3',quantity:1}]}).deliveryFeeCup===1400);
check(quote({cart:[cart[0],cart[0]]}).deliveryFeeCup===600);
check(quote({cart:[{productId:'missing',quantity:1}]}).reason==='ASSOCIATION_MISSING');
check(quote({associations:{...associations,p1:[]}}).reason==='ASSOCIATION_INVALID');
check(quote({associations:{...associations,p1:['a','a']}}).reason==='ASSOCIATION_INVALID');
check(quote({associations:{...associations,p1:['ghost']}}).reason==='ASSOCIATION_INVALID');
check(quote({configuration:{...configuration,origins:configuration.origins.map(o=>o.id==='a'?{...o,active:false}:o)}}).reason==='ORIGIN_INACTIVE');
check(quote({configuration:{...configuration,suppliers:[{...configuration.suppliers[0],active:false}]}}).reason==='ORIGIN_INACTIVE');
check(quote({expectedRevision:4}).reason==='STALE_REVISION');
check(quote({cart:[]}).reason==='INVALID_CART');
check(quote({cart:[{productId:'p1',quantity:0}]}).reason==='INVALID_CART');
check(quote({routes:[]}).reason==='ROAD_DISTANCE_MISSING');
check(quote({specialFeeCup:900}).deliveryFeeCup===900);
check(quote().productTotalAdjustment===0&&quote().collection==='DIRECT_TO_COURIER');
check(quote().simulationOnly===true);
check(quote({quarantined:true}).reason==='QUARANTINE');
check(quote({cart:[{productId:'p1',quantity:1}],routes:[routes[0]]}).deliveryFeeCup===600);
check(quote({cart:[{productId:'p1',quantity:1}],routes:[routes[1]]}).reason==='ROAD_DISTANCE_MISSING');
check(quote({cart:[{productId:'p1',quantity:1}],specialFeeCup:750}).deliveryFeeCup===750);
console.log('PASS '+count+' cart-origin offline assertions');
