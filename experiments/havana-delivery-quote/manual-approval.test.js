'use strict';
const assert=require('node:assert/strict');
const {snapshot,requestManualQuote,approveManualQuote,resolveManualQuote}=require('./manual-approval.js');
const config={schemaVersion:1,revision:8,suppliers:[],origins:[{id:'a',name:'Almacén',type:'propio',active:true}],destinations:[{id:'d',name:'Destino',municipality:'Playa',address:'Ficticia'},{id:'e',name:'Otro',municipality:'Playa',address:'Ficticia'}]};
const base={configuration:config,expectedRevision:8,cart:[{productId:'p',quantity:1},{productId:'q',quantity:1}],associations:{p:['a'],q:['a']},destinationId:'d',productDeliveryRules:[{productId:'p',mode:'special',feeCup:900},{productId:'q',mode:'normal'}]};
const request=requestManualQuote(base).request;
const approved=approveManualQuote({request,actor:{id:'admin1',role:'principal'},feeCup:1100,approvalId:'approval1',issuedAt:'2026-11-18T12:00:00Z'});
const now='2026-11-18T12:01:00Z';
let n=0;const check=x=>{assert.ok(x);n++};
check(requestManualQuote(base).reason==='MANUAL_APPROVAL_REQUIRED');
check(request.fingerprint.length===64);
check(approved.status==='APPROVAL_DRAFT');
check(resolveManualQuote({...base,approval:approved,now}).status==='APROBACION_MANUAL_SIMULADA');
check(resolveManualQuote({...base,approval:approved,now}).deliveryFeeCup===1100);
check(resolveManualQuote({...base,approval:approved,now}).productTotalAdjustment===0);
check(resolveManualQuote({...base,approval:approved,now}).collection==='DIRECT_TO_COURIER');
check(resolveManualQuote({...base,approval:approved,now}).simulationOnly===true);
check(resolveManualQuote({...base,approval:null,now}).reason==='APPROVAL_MISSING_OR_STALE');
check(resolveManualQuote({...base,approval:approved,now,cart:[{productId:'p',quantity:2},{productId:'q',quantity:1}]}).reason==='APPROVAL_MISSING_OR_STALE');
check(resolveManualQuote({...base,approval:approved,now,destinationId:'e'}).reason==='APPROVAL_MISSING_OR_STALE');
check(resolveManualQuote({...base,approval:approved,now,configuration:{...config,revision:9},expectedRevision:9}).reason==='APPROVAL_MISSING_OR_STALE');
check(resolveManualQuote({...base,approval:approved,now,quarantined:true}).reason==='QUARANTINE');
check(resolveManualQuote({...base,approval:approved,now:'2026-11-18T12:16:00Z'}).reason==='APPROVAL_EXPIRED');
check(resolveManualQuote({...base,approval:approved,now:'2026-11-18T11:59:00Z'}).reason==='APPROVAL_EXPIRED');
check(approveManualQuote({request,actor:{id:'x',role:'supervisor'},feeCup:100,approvalId:'x',issuedAt:now}).reason==='UNAUTHORIZED_ROLE');
check(approveManualQuote({request,actor:{id:'x',role:'gestor'},feeCup:100,approvalId:'x',issuedAt:now}).reason==='UNAUTHORIZED_ROLE');
check(approveManualQuote({request,actor:{id:'x',role:'general'},feeCup:100,approvalId:'x',issuedAt:now}).status==='APPROVAL_DRAFT');
check(approveManualQuote({request,actor:{id:'x',role:'principal'},feeCup:-1,approvalId:'x',issuedAt:now}).reason==='INVALID_APPROVAL');
check(requestManualQuote({...base,cart:[{productId:'p',quantity:1}]}).reason==='MANUAL_NOT_REQUIRED');
check(requestManualQuote({...base,associations:{p:['missing'],q:['a']}}).reason==='ASSOCIATION_INVALID');
check(snapshot({...base,productDeliveryRules:[]}).reason==='RULE_MISSING');
check(snapshot({...base,cart:[...base.cart].reverse()}).fingerprint===request.fingerprint);
console.log('PASS '+n+' offline manual-approval assertions');
