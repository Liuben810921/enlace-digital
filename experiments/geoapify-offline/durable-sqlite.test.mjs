import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';import {tmpdir} from 'node:os';import {join} from 'node:path';
import {QuotaLab,fixtureSession} from './durable-sqlite.mjs';
const dir=mkdtempSync(join(tmpdir(),'ed-quota-')),file=join(dir,'quota.sqlite');
let now=Date.UTC(2026,10,18),clock=()=>now,key='fixture-only',n=0;
const check=(a,b)=>{assert.deepEqual(a,b);n++};
const s=fixtureSession(key,'synthetic',now+100000);
const q=new QuotaLab({file,key,limit:2,clock});
check(q.reserve({session:{...s,signature:'x'},nonce:'nonce-0001'}).reason,'AUTH');
check(q.reserve({session:{...s,expires:now-1},nonce:'nonce-0001'}).reason,'AUTH');
check(q.reserve({session:s,nonce:'bad'}).reason,'INVALID');
check(q.reserve({session:s,nonce:'nonce-0001',credits:3}).reason,'INVALID');
const results=await Promise.all(Array.from({length:30},(_,i)=>Promise.resolve().then(()=>q.reserve({session:s,nonce:'nonce-'+String(i).padStart(5,'0')}))));
check(results.filter(r=>r.status==='RESERVED').length,2);
check(results.filter(r=>r.reason==='QUOTA').length,28);
check(q.stats(),{used:0,reserved:2});
check(q.reserve({session:s,nonce:'nonce-00000'}).reason,'REPLAY');
check(q.settle('nonce-00000',{success:true}).status,'CONSUMED');
check(q.settle('nonce-00001',{success:false}).status,'PENDIENTE');
check(q.stats(),{used:2,reserved:0});
check(q.settle('nonce-00000').reason,'REPLAY_OR_UNKNOWN');
q.close();
const recovered=new QuotaLab({file,key,limit:2,clock});
check(recovered.stats(),{used:2,reserved:0});
check(recovered.reserve({session:s,nonce:'nonce-99999'}).reason,'QUOTA');
now+=86400000;const s2=fixtureSession(key,'synthetic',now+100000);
check(recovered.reserve({session:s2,nonce:'nonce-99999'}).status,'RESERVED');
check(recovered.stats(),{used:0,reserved:1});
recovered.close();rmSync(dir,{recursive:true,force:true});
console.log('PASS '+n+' SQLite offline assertions; 2/30 accepted');
